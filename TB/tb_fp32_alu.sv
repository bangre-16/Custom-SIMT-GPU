`timescale 1ns/1ps

module tb_fp32_alu;

    logic [31:0] A;
    logic [31:0] B;
    logic [31:0] C;
    logic [2:0]  fp_op;

    logic [31:0] result;
    logic        zero;

    integer pass_count;
    integer fail_count;

    localparam logic [2:0] FP_ADD = 3'b000;
    localparam logic [2:0] FP_SUB = 3'b001;
    localparam logic [2:0] FP_MUL = 3'b010;
    localparam logic [2:0] FP_FMA = 3'b011;

    // Instantiate FP32 ALU
    fp32_alu dut (
        .A(A),
        .B(B),
        .C(C),
        .fp_op(fp_op),
        .result(result),
        .zero(zero)
    );

    // =========================================================
    // Result checking task
    // =========================================================
    task check_result(
        input logic [31:0] expected,
        input string test_name
    );
        begin
            #1;

            if (result === expected) begin
                $display("%-12s : PASS | Result = %h",
                         test_name, result);
                pass_count = pass_count + 1;
            end
            else begin
                $display("%-12s : FAIL | Expected = %h | Got = %h",
                         test_name, expected, result);
                fail_count = fail_count + 1;
            end
        end
    endtask


    // =========================================================
    // TEST SEQUENCE
    // =========================================================
    initial begin

        pass_count = 0;
        fail_count = 0;

        A = 32'b0;
        B = 32'b0;
        C = 32'b0;
        fp_op = FP_ADD;

        $display("========================================");
        $display("        CUSTOM GPU FP32 ALU TEST");
        $display("========================================");


        // =====================================================
        // TEST 1
        // 1.0 + 2.0 = 3.0
        // =====================================================
        A = 32'h3F800000;      // 1.0
        B = 32'h40000000;      // 2.0
        C = 32'h00000000;
        fp_op = FP_ADD;

        check_result(32'h40400000, "FADD");


        // =====================================================
        // TEST 2
        // 5.0 - 2.0 = 3.0
        // =====================================================
        A = 32'h40A00000;      // 5.0
        B = 32'h40000000;      // 2.0
        C = 32'h00000000;
        fp_op = FP_SUB;

        check_result(32'h40400000, "FSUB");


        // =====================================================
        // TEST 3
        // 2.0 × 4.0 = 8.0
        // =====================================================
        A = 32'h40000000;      // 2.0
        B = 32'h40800000;      // 4.0
        C = 32'h00000000;
        fp_op = FP_MUL;

        check_result(32'h41000000, "FMUL");


        // =====================================================
        // TEST 4
        // 0.0 + 0.0 = 0.0
        // =====================================================
        A = 32'h00000000;
        B = 32'h00000000;
        C = 32'h00000000;
        fp_op = FP_ADD;

        check_result(32'h00000000, "FADD_ZERO");


        // =====================================================
        // TEST 5
        // 10.0 - 10.0 = 0.0
        // =====================================================
        A = 32'h41200000;      // 10.0
        B = 32'h41200000;      // 10.0
        C = 32'h00000000;
        fp_op = FP_SUB;

        check_result(32'h00000000, "FSUB_ZERO");


        // =====================================================
        // TEST 6
        // -2.0 + 1.0 = -1.0
        // =====================================================
        A = 32'hC0000000;      // -2.0
        B = 32'h3F800000;      // 1.0
        C = 32'h00000000;
        fp_op = FP_ADD;

        check_result(32'hBF800000, "FADD_NEG");


        // =====================================================
        // TEST 7
        // 4.0 × -2.0 = -8.0
        // =====================================================
        A = 32'h40800000;      // 4.0
        B = 32'hC0000000;      // -2.0
        C = 32'h00000000;
        fp_op = FP_MUL;

        check_result(32'hC1000000, "FMUL_NEG");


        // =====================================================
        // TEST 8
        // FFMA
        //
        // 2.0 × 3.0 + 4.0 = 10.0
        // =====================================================
        A = 32'h40000000;      // 2.0
        B = 32'h40400000;      // 3.0
        C = 32'h40800000;      // 4.0
        fp_op = FP_FMA;

        check_result(32'h41200000, "FFMA");


        // =====================================================
        // TEST 9
        // FFMA negative
        //
        // (-2.0 × 3.0) + 4.0 = -2.0
        // =====================================================
        A = 32'hC0000000;      // -2.0
        B = 32'h40400000;      // 3.0
        C = 32'h40800000;      // 4.0
        fp_op = FP_FMA;

        check_result(32'hC0000000, "FFMA_NEG");


        // =====================================================
        // FINAL RESULTS
        // =====================================================
        $display("----------------------------------------");
        $display("PASSED : %0d", pass_count);
        $display("FAILED : %0d", fail_count);
        $display("----------------------------------------");

        if (fail_count == 0)
            $display("ALL FP32 TESTS PASSED");
        else
            $display("FP32 TESTS FAILED");

        $display("========================================");

        #10;
        $finish;

    end

endmodule